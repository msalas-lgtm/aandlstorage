-- A&L Self Storage: database tables, phase 1 (website content).
-- Run this once in Supabase: SQL Editor > New query > paste > Run.
-- Safe to run again: every statement uses "if not exists".

-- One row of site-wide settings (phone, email, address, hours, social links, ...).
create table if not exists public.site_settings (
  id          int primary key default 1 check (id = 1),
  data        jsonb not null,
  updated_at  timestamptz not null default now()
);

-- The public pages: titles, descriptions and menu labels. The path (URL) never changes.
create table if not exists public.pages (
  path              text primary key,
  title             text not null,
  description       text not null default '',
  tab_name          text,
  tab_visible       boolean not null default true,
  footer_link_text  text not null default '',
  login_link_text   text not null default '',
  priority          numeric,
  updated_at        timestamptz not null default now()
);

-- Blog posts. The slug is the URL (/blog/<slug>) and keeps the live site's exact spelling.
create table if not exists public.blog_posts (
  slug              text primary key check (slug ~ '^[A-Za-z0-9][A-Za-z0-9_-]*$'),
  title             text not null,
  published_at      timestamptz not null,
  meta_title        text not null default '',
  meta_description  text not null default '',
  html              text not null,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- Unit types and monthly prices shown on the Rent page and used by the admin Unit Types page.
create table if not exists public.unit_types (
  id            bigint generated by default as identity primary key,
  name          text not null unique,
  units_count   int not null default 0,
  price_cents   int not null check (price_cents >= 0),
  description   text not null default '',
  image_path    text not null default '',
  on_website    boolean not null default false,
  availability  text not null default 'rent' check (availability in ('rent', 'waiting')),
  note          text not null default '',
  sort_order    int not null default 0,
  updated_at    timestamptz not null default now()
);

-- Titles and alt text for images (the files themselves live in Supabase Storage or /public).
create table if not exists public.images (
  key         text primary key,
  kind        text not null default 'library',
  title       text not null default '',
  alt         text not null default '',
  created_at  timestamptz not null default now()
);

-- Messages sent from the website contact form.
create table if not exists public.contact_messages (
  id          bigint generated always as identity primary key,
  name        text not null,
  email       text not null,
  phone       text not null default '',
  message     text not null,
  status      text not null default 'new' check (status in ('new', 'read', 'archived')),
  created_at  timestamptz not null default now()
);

-- Lock every table. No policies means the public (browser) keys can't read or write anything.
-- The site's server uses the secret key, which bypasses this, so all access stays behind the admin login.
alter table public.site_settings    enable row level security;
alter table public.pages            enable row level security;
alter table public.blog_posts       enable row level security;
alter table public.unit_types       enable row level security;
alter table public.images           enable row level security;
alter table public.contact_messages enable row level security;
